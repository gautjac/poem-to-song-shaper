// build-rhyme-dict.mjs
// Downloads the CMU pronouncing dictionary, extracts rhyme keys for the
// ~20K most common English words, and writes a compact JS module into
// netlify/functions/rhyme-dict.js so the propose function can use real
// phonetic rhyme detection instead of spelling-based heuristics.
//
// Run:    node scripts/build-rhyme-dict.mjs
// Output: netlify/functions/rhyme-dict.js

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT      = path.resolve(__dirname, "..");
const OUT_PATH  = path.join(ROOT, "netlify", "functions", "rhyme-dict.js");

const CMU_URL  = "https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict";
// 20K most common English words — generous enough to cover poetic
// vocabulary (eyes, sky, lay, still) without bloating the bundle.
const WORDS_URL = "https://raw.githubusercontent.com/first20hours/google-10000-english/master/20k.txt";

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Failed to fetch ${url}: ${res.status}`);
  return await res.text();
}

// Compute the rhyme key of a CMU phoneme array.
// Phonemes look like: ["S", "K", "AY1", "Z"] for "skies".
// The rhyme is the last *primary or secondary stressed* vowel and everything
// after it. Stress is encoded as a digit suffix on vowel phonemes:
//   0 = unstressed, 1 = primary stress, 2 = secondary stress.
// Rule: walk from the end, find the most recent vowel with stress 1; if none,
// fall back to last vowel with any stress; strip stress markers from the
// final key (they aren't part of the rhyme sound).
function rhymeKeyFromPhonemes(phonemes) {
  if (!phonemes || !phonemes.length) return "";
  let cut = -1;
  // Prefer the last primary-stressed vowel.
  for (let i = phonemes.length - 1; i >= 0; i--) {
    if (/\d/.test(phonemes[i]) && phonemes[i].endsWith("1")) { cut = i; break; }
  }
  // Otherwise any stressed vowel.
  if (cut === -1) {
    for (let i = phonemes.length - 1; i >= 0; i--) {
      if (/\d/.test(phonemes[i])) { cut = i; break; }
    }
  }
  if (cut === -1) return phonemes.join(" ");
  return phonemes.slice(cut)
    .map(p => p.replace(/\d/g, ""))
    .join(" ");
}

function main() {
  return Promise.all([fetchText(CMU_URL), fetchText(WORDS_URL)]).then(([cmuRaw, wordsRaw]) => {
    const allowed = new Set(
      wordsRaw.split(/\r?\n/).map(w => w.trim().toLowerCase()).filter(Boolean)
    );
    console.log(`common-words list: ${allowed.size} words`);

    // Add some common poetic words that may not be in the medium list.
    [
      "ye","thee","thou","thy","thine","whence","hither","thither","yonder",
      "alas","farewell","heretofore","henceforth","forevermore","amen",
      "oh","ah","oer","tis","twas","ere","unto","wherefore","fro",
      "shadow","shadows","glimmer","whisper","whispered","trembled","trembling",
      "linger","lingered","forsaken","forsook","weep","wept","mourn","mourned"
    ].forEach(w => allowed.add(w));

    const out = {};
    let kept = 0, skipped = 0;
    const lines = cmuRaw.split(/\r?\n/);
    for (const line of lines) {
      if (!line || line.startsWith(";;;")) continue;
      // CMU line format: "word ph1 ph2 ph3 ..."
      // Variants may have parens: "word(2) ph1 ph2 ..."  — keep the base form.
      const sp = line.indexOf(" ");
      if (sp < 0) continue;
      let word  = line.slice(0, sp).toLowerCase();
      const phs = line.slice(sp + 1).trim().split(/\s+/);
      // Strip variant suffix like "(2)"
      word = word.replace(/\(\d+\)$/, "");
      if (!allowed.has(word)) { skipped++; continue; }
      // If the word already has an entry (multi-pron), keep the first; that's
      // typically the most common pronunciation in CMU.
      if (out[word]) continue;
      const key = rhymeKeyFromPhonemes(phs);
      if (!key) continue;
      out[word] = key;
      kept++;
    }
    console.log(`kept: ${kept}  skipped: ${skipped}`);

    // Write as a compact JS module. JSON-stringify with no indent for size.
    const json = JSON.stringify(out);
    const fileBody =
`// AUTO-GENERATED — do not edit by hand.
// Generated by scripts/build-rhyme-dict.mjs from the CMU Pronouncing
// Dictionary, intersected with a common-English word list.
// Each entry maps a lowercase word to its rhyme key (the last stressed
// vowel and everything after, with stress markers stripped).
// Two words rhyme when their rhyme keys are identical.

export const RHYME_DICT = ${json};

// Convenience lookup. Returns "" if the word is unknown.
export function rhymeKey(word) {
  if (!word) return "";
  return RHYME_DICT[word.toLowerCase().replace(/[^a-z']/g, "")] || "";
}

export const META = {
  source: "CMU Pronouncing Dictionary 0.7b",
  generatedAt: ${JSON.stringify(new Date().toISOString())},
  size: ${kept}
};
`;
    fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
    fs.writeFileSync(OUT_PATH, fileBody, "utf8");
    const stat = fs.statSync(OUT_PATH);
    console.log(`wrote ${OUT_PATH}  (${(stat.size / 1024).toFixed(1)} KB)`);
  });
}

main().catch(err => { console.error(err); process.exit(1); });
