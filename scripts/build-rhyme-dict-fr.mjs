// build-rhyme-dict-fr.mjs
// Downloads Lexique 3.83 (~143K French words with SAMPA-like phonetic
// transcriptions), filters to the most frequent ~25K, computes rhyme keys,
// and writes netlify/functions/rhyme-dict-fr.js so the propose function can
// use real phonetic French rhyme detection (not spelling guesses).
//
// Run:    node scripts/build-rhyme-dict-fr.mjs
// Output: netlify/functions/rhyme-dict-fr.js
//
// Lexique 3.83 phon column uses these symbols:
//   Pure vowels:   a A e E i o O u y 2 9
//   Nasal vowels:  5 (ɔ̃)  1 (ɛ̃)  @ (ɑ̃)
//   Schwa / e-muet: °     (optional in pronunciation, often dropped at end)
//   Glides:        j w 8
//   Consonants:    p t k b d g f s S v z Z m n l R N G x
//
// Rhyme key = from the last vowel onward (with trailing ° stripped, since
// the e-muet at the end of a line is conventionally silent in song).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT      = path.resolve(__dirname, "..");
const OUT_PATH  = path.join(ROOT, "netlify", "functions", "rhyme-dict-fr.js");

const LEXIQUE_URL = "http://www.lexique.org/databases/Lexique383/Lexique383.tsv";

const VOWELS = new Set([
  "a","A","e","E","i","o","O","u","y","2","9",
  "5","1","@",
  "°"
]);

// Pure (non-nasal, non-schwa) vowels — used to skip a trailing e-muet.
const TRAILING_DROPPABLE = new Set(["°"]);

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Failed to fetch ${url}: ${res.status}`);
  return await res.text();
}

// Compute the rhyme key for a Lexique-formatted phonemic string.
// Strategy:
//   1. Drop trailing schwa (°) — silent in conventional song endings.
//   2. Find the LAST vowel character (including nasals).
//   3. Return phon.slice(lastVowelIndex).
// Two words rhyme when their keys are identical.
function rhymeKeyFromPhon(phon) {
  if (!phon) return "";
  let p = phon;
  while (p.length && TRAILING_DROPPABLE.has(p[p.length - 1])) {
    p = p.slice(0, -1);
  }
  if (!p) return "";
  let lastVowelIdx = -1;
  for (let i = 0; i < p.length; i++) {
    if (VOWELS.has(p[i])) lastVowelIdx = i;
  }
  if (lastVowelIdx < 0) return p.slice(-2);
  return p.slice(lastVowelIdx);
}

function main() {
  return fetchText(LEXIQUE_URL).then(raw => {
    const lines = raw.split(/\r?\n/);
    if (lines.length < 100) throw new Error("Lexique download looks truncated");

    // Parse header to find columns by name (defensive against minor format drift).
    const header = lines[0].split("\t");
    const idxOrtho = header.indexOf("ortho");
    const idxPhon  = header.indexOf("phon");
    const idxFL    = header.indexOf("freqlemlivres");
    const idxFF    = header.indexOf("freqlemfilms2");
    const idxFLem  = header.indexOf("islem");
    if (idxOrtho < 0 || idxPhon < 0) throw new Error("Lexique header missing ortho/phon");

    // Aggregate per-word: keep best (highest-frequency) entry per ortho.
    const best = new Map();
    let parsed = 0;
    for (let i = 1; i < lines.length; i++) {
      const line = lines[i];
      if (!line) continue;
      const cols = line.split("\t");
      const ortho = (cols[idxOrtho] || "").toLowerCase();
      const phon  = cols[idxPhon] || "";
      if (!ortho || !phon) continue;
      // Skip multi-word entries (with spaces) — those distort rhyme.
      if (/\s/.test(ortho)) continue;
      // Skip pure punctuation / numeric tokens.
      if (!/[a-zàâäéèêëîïôöùûüÿç]/i.test(ortho)) continue;
      const fl = parseFloat(cols[idxFL]) || 0;
      const ff = parseFloat(cols[idxFF]) || 0;
      const freq = fl + ff;
      const cur = best.get(ortho);
      if (!cur || cur.freq < freq) best.set(ortho, { phon, freq });
      parsed++;
    }
    console.log(`parsed: ${parsed} rows, ${best.size} unique orthographic forms`);

    // Keep any word with at least minimal frequency in either corpus.
    // 0.5 catches poetic / literary vocabulary (ambre 0.93, ronces 0.7,
    // ardoise 0.4) that strict top-N cuts off, while excluding the long
    // tail of typos and very rare conjugations.
    const MIN_FREQ = 0.5;
    const sorted = [...best.entries()]
      .filter(([, v]) => v.freq >= MIN_FREQ)
      .sort((a, b) => b[1].freq - a[1].freq);

    const out = {};
    for (const [word, { phon }] of sorted) {
      const key = rhymeKeyFromPhon(phon);
      if (!key) continue;
      out[word] = key;
    }
    console.log(`kept ${Object.keys(out).length} words`);

    const json = JSON.stringify(out);
    const fileBody =
`// AUTO-GENERATED — do not edit by hand.
// Generated by scripts/build-rhyme-dict-fr.mjs from Lexique 3.83
// (http://www.lexique.org), keeping the most frequent ~25K orthographic
// forms. Each entry maps a lowercase French word to its rhyme key
// (the last vowel and everything after, with the trailing schwa °
// already stripped). Two words rhyme when their keys are identical.
//
// Phoneme alphabet is Lexique's SAMPA-like notation (R for French R,
// S for ʃ, Z for ʒ, 5 for ɔ̃, 1 for ɛ̃, @ for ɑ̃, ° for schwa, etc.).

export const RHYME_DICT_FR = ${json};

export function rhymeKey(word) {
  if (!word) return "";
  // Lowercase, expand ligatures (Lexique stores "coeur" not "cœur"),
  // then strip everything that isn't a French letter or apostrophe.
  const k = word.toLowerCase()
    .replace(/œ/g, "oe").replace(/æ/g, "ae")
    .replace(/[^a-zàâäéèêëîïôöùûüÿç']/gi, "");
  return RHYME_DICT_FR[k] || "";
}

export const META = {
  source:     "Lexique 3.83",
  generatedAt: ${JSON.stringify(new Date().toISOString())},
  size:       ${Object.keys(out).length}
};
`;
    fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
    fs.writeFileSync(OUT_PATH, fileBody, "utf8");
    const stat = fs.statSync(OUT_PATH);
    console.log(`wrote ${OUT_PATH}  (${(stat.size / 1024).toFixed(1)} KB)`);
  });
}

main().catch(err => { console.error(err); process.exit(1); });
